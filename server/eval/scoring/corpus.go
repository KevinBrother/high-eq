// Command scoring is an offline evaluation tool. It has no provider client.
package main

import (
	"bufio"
	"bytes"
	_ "embed"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"strings"

	"high-eq/server/internal/scoring"
)

//go:embed cases.jsonl
var corpus []byte

type label struct {
	Mode    string `json:"mode"`
	NVC     []int  `json:"nvc"`
	Total   int    `json:"total"`
	Emotion []int  `json:"emotion"`
}
type sample struct {
	Case        int             `json:"case"`
	Scene       string          `json:"scene"`
	Turns       []scoring.Turn  `json:"turns"`
	LabelStatus string          `json:"label_status"`
	Expected    label           `json:"expected"`
	Reference   json.RawMessage `json:"reference_output,omitempty"`
}

func (s sample) userTurns() int {
	n := 0
	for _, t := range s.Turns {
		if t.Role == "user" {
			n++
		}
	}
	return n
}
func (v label) valid() bool {
	if len(v.NVC) != 4 || len(v.Emotion) != 3 || (v.Mode != "express" && v.Mode != "respond") {
		return false
	}
	sum := 0
	for _, n := range v.NVC {
		switch n {
		case 0, 5, 10, 15, 25:
			sum += n
		default:
			return false
		}
	}
	for _, n := range v.Emotion {
		if n < 1 || n > 5 {
			return false
		}
	}
	return sum == v.Total
}
func decode(line []byte, dst any) error {
	dec := json.NewDecoder(bytes.NewReader(line))
	dec.DisallowUnknownFields()
	if dec.Decode(dst) != nil || dec.Decode(new(any)) != io.EOF {
		return errors.New("invalid JSONL record")
	}
	return nil
}
func loadCases() ([]sample, error) {
	var cs []sample
	multi := 0
	for i, line := range bytes.Split(bytes.TrimSpace(corpus), []byte("\n")) {
		var s sample
		if decode(line, &s) != nil || s.Case != i+1 || !s.Expected.valid() || s.userTurns() == 0 || strings.TrimSpace(s.Scene) == "" {
			return nil, fmt.Errorf("invalid corpus row %d", i+1)
		}
		switch {
		case i < 10:
			if s.LabelStatus != "规范参照" {
				return nil, errors.New("invalid baseline provenance")
			}
		case i < 12:
			if s.LabelStatus != "规范回归" {
				return nil, errors.New("invalid regression provenance")
			}
			v, err := scoring.ParseFull(s.Reference, s.userTurns())
			if err != nil || v.NVC.Total != s.Expected.Total || !regression(s.Case, v) {
				return nil, errors.New("invalid regression reference")
			}
		default:
			if s.LabelStatus != "待人工复核" {
				return nil, errors.New("draft is not human evidence")
			}
			if s.userTurns() > 1 {
				multi++
			}
		}
		cs = append(cs, s)
	}
	if len(cs) != 32 || multi < 5 {
		return nil, errors.New("corpus coverage")
	}
	return cs, nil
}

// Sidecar records are independent project attestations, never generated by this tool.
func applyReviews(cs []sample, r io.Reader) error {
	scan := bufio.NewScanner(r)
	for scan.Scan() {
		var v struct {
			Case     int    `json:"case"`
			Status   string `json:"label_status"`
			Expected label  `json:"expected"`
		}
		if decode(scan.Bytes(), &v) != nil || v.Status != "已人工复核" || v.Case < 13 || v.Case > len(cs) || !v.Expected.valid() || cs[v.Case-1].LabelStatus != "待人工复核" {
			return errors.New("invalid or duplicate human review")
		}
		cs[v.Case-1].Expected = v.Expected
		cs[v.Case-1].LabelStatus = v.Status
	}
	return scan.Err()
}
